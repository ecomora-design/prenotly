import { NextResponse } from "next/server";
import { createClient } from "@/lib/supabase/server";
import { createAdminClient } from "@/lib/supabase/admin";

export async function POST(req: Request, { params }: { params: Promise<{ id: string }> }) {
  try {
    const { id } = await params;
    const { status } = await req.json();

    if (!status || !["preparing", "ready"].includes(status)) {
      return NextResponse.json({ error: "status deve essere 'preparing' o 'ready'" }, { status: 400 });
    }

    const supabase = await createClient();
    const { data: { user } } = await supabase.auth.getUser();
    if (!user) return NextResponse.json({ error: "Non autenticato" }, { status: 401 });

    const admin = createAdminClient();
    const { data: order } = await admin.from("table_orders").select("*").eq("id", id).single();
    if (!order) return NextResponse.json({ error: "Comanda non trovata" }, { status: 404 });

    // Solo comande in stati "attivi"
    if (!["sent", "sent_partial", "preparing", "ready"].includes(order.status)) {
      return NextResponse.json({ error: "Comanda non è in cucina" }, { status: 400 });
    }

    // Verifica autorizzazione (staff cucina o both, o titolare)
    const { data: owner } = await admin
      .from("tenant_users")
      .select("tenant_id")
      .eq("user_id", user.id)
      .eq("tenant_id", order.tenant_id)
      .maybeSingle();
    let isAuthorized = !!owner;
    if (!isAuthorized) {
      const { data: staffRow } = await admin
        .from("staff")
        .select("id, reparto")
        .eq("user_id", user.id)
        .eq("tenant_id", order.tenant_id)
        .eq("is_active", true)
        .maybeSingle();
      isAuthorized = !!staffRow && (staffRow.reparto === "kitchen" || staffRow.reparto === "both");
    }
    if (!isAuthorized) return NextResponse.json({ error: "Non autorizzato (solo cucina può aggiornare)" }, { status: 403 });

    const { data: updated, error } = await admin
      .from("table_orders")
      .update({ status })
      .eq("id", id)
      .select()
      .single();

    if (error) return NextResponse.json({ error: error.message }, { status: 500 });

    return NextResponse.json({ order: updated });
  } catch (err: any) {
    return NextResponse.json({ error: err.message || "Errore" }, { status: 500 });
  }
}
